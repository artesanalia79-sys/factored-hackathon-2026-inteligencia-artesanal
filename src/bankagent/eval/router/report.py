"""Render a router evaluation as ``docs/evidence/router_eval.md`` (Task 18).

Deterministic: no timings, no environment details, so regenerating it on the same corpus gives
the same file (another CPU's BLAS kernels may move a printed decimal by one unit). Timings and the
artifact size go to the MLflow run and the console instead.
"""

from __future__ import annotations

import math
import statistics
from collections import Counter
from collections.abc import Iterable, Sequence

from bankagent.contracts.enums import Intent
from bankagent.eval.metrics import Rate
from bankagent.eval.router.evaluate import (
    C_GRID,
    INNER_FOLDS,
    KEYWORD_ANSWER_CONFIDENCE,
    Classification,
    Evaluation,
)
from bankagent.router.model import MIN_DF, NGRAM_RANGE

INTENTS: tuple[Intent, ...] = tuple(Intent)
SHORT = {  # the corpus group-id prefixes
    Intent.DISPUTE_UNRECOGNIZED: "unr",
    Intent.DISPUTE_DUPLICATE: "dup",
    Intent.DISPUTE_NOT_RECEIVED: "nrc",
    Intent.CARD_BLOCK: "blk",
    Intent.DISPUTE_STATUS: "sta",
    Intent.HUMAN_REQUEST: "hum",
    Intent.OUT_OF_SCOPE: "oos",
    Intent.ATTACK: "atk",
}


def _share(rate: Rate) -> str:
    if rate.point is None:
        return "n/a (0/0)"
    return f"{rate.point:.1%} ({rate.successes}/{rate.n})"


def _interval(rate: Rate, interval: tuple[float, float] | None = None) -> str:
    if rate.point is None:
        return "n/a"
    interval = rate.interval if interval is None else interval
    return "n/a" if interval is None else f"[{interval[0]:.1%}, {interval[1]:.1%}]"


def _with_interval(rate: Rate, interval: tuple[float, float] | None = None) -> str:
    return f"{_share(rate)} {_interval(rate, interval)}"


def _number(value: float) -> str:
    return f"{value:g}"


def _table(header: Sequence[str], rows: Iterable[Sequence[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return lines


def _spread(values: Sequence[float]) -> tuple[str, str, str]:
    """Mean, min and max over the splits that have the value: a split where the router never
    answers has no accuracy when answering (NaN)."""
    present = [v for v in values if not math.isnan(v)]
    if not present:
        return ("n/a", "n/a", "n/a")
    return (
        f"{statistics.fmean(present):.1%}",
        f"{min(present):.1%}",
        f"{max(present):.1%}",
    )


def _confusion(result: Classification) -> list[str]:
    header = ["true \\ predicted", *(SHORT[i] for i in INTENTS)]
    rows = [[SHORT[t], *(str(result.confusion[t][p]) for p in INTENTS)] for t in INTENTS]
    return _table(header, rows)


def render_report(evaluation: Evaluation) -> str:
    ev = evaluation
    router = ev.trained.router
    examples = ev.corpus.examples
    splits = ev.trained.splits
    reviewers = sorted({r for r in ev.corpus.reviewed_by.values() if r})
    pending = [i.value for i, r in ev.corpus.reviewed_by.items() if not r]
    review = (
        ", ".join(reviewers) + (f"; pending for {', '.join(pending)}" if pending else "")
        if reviewers
        else "pending (a teammate reviews a sample before merge)"
    )
    groups = {e.group for e in examples}
    dialects = {e.dialect for e in examples}
    test_groups = {examples[i].group for i in splits.test}
    c_scores = ", ".join(
        f"{_number(c)}: {ev.trained.c_scores[c]:.3f}" for c in sorted(ev.trained.c_scores)
    )
    lines = [
        "# Learned router evaluation (Task 18)",
        "",
        "Generated by `uv run poe router`; do not edit by hand. Model card:",
        "`docs/models/router.md`.",
        "",
        "Every message here is synthetic. The corpus was written by one author (the AI assistant",
        "that built this task), so the test split comes from the same hand as the training data:",
        "these numbers measure the method on that distribution, not accuracy on real customers.",
        "",
        f"- Model: `{router.version}`: TF-IDF character n-grams"
        f" {NGRAM_RANGE[0]}-{NGRAM_RANGE[1]} inside word",
        f"  boundaries (min_df {MIN_DF}) on the keyword normalization, then a class-balanced",
        f"  logistic regression; scenario-calibrated split-conformal abstention with"
        f" α = {_number(ev.alpha)}.",
        f"- Corpus: {len(examples)} messages, {len(groups)} scenario groups, {len(INTENTS)}"
        f" intents, {len(dialects)} dialects.",
        f"- Corpus sha256: `{ev.corpus.sha256}`",
        f"- External check sha256: `{ev.external_sha256}`",
        f"- Corpus review: {review}.",
        f"- Split seed {ev.seed}. C = {_number(ev.trained.c)}, chosen from"
        f" {{{', '.join(_number(c) for c in C_GRID)}}} by grouped",
        f"  {INNER_FOLDS}-fold cross-validation inside the fit split (mean macro-F1 per C:",
        f"  {c_scores}). Calibration takes the worst score in each scenario;"
        f" q̂ = {router.q_hat:.4f}.",
        "",
        "## Splits",
        "",
        "Stratified by intent and grouped by scenario: the five dialect versions of a scenario",
        "are always in the same split. The 32 calibration scenarios, not their 160 messages,",
        "are the units used to choose the conformal threshold. Under exchangeable scenarios",
        "the prediction set covers all five dialect versions of a new scenario with probability",
        f"at least {1 - ev.alpha:.0%}; this is marginal over scenarios, not each intent"
        " or dialect.",
        "",
    ]
    split_rows = []
    for name, idx in (
        ("fit", splits.fit),
        ("calibration", splits.calibration),
        ("test", splits.test),
    ):
        counts = ev.split_counts[name]
        per_intent = ", ".join(f"{SHORT[i]} {counts[i]}" for i in INTENTS)
        split_rows.append(
            [name, str(len(idx)), str(len({examples[i].group for i in idx})), per_intent]
        )
    lines += _table(["Split", "Messages", "Groups", "Per intent"], split_rows)

    lines += [
        "",
        "## Test split: learned vs. keyword router",
        "",
        "The 95% percentile intervals resample whole scenario groups (5 dialect versions",
        "together, 5,000 draws). They describe uncertainty on this synthetic scenario source,",
        "not on real customer traffic.",
        "",
    ]
    lines += _table(
        ["Router", "Accuracy [95% scenario bootstrap interval]", "Macro-F1"],
        [
            [
                "Learned (top-1)",
                _with_interval(ev.learned.accuracy, ev.test_intervals["learned_accuracy"]),
                f"{ev.learned.macro_f1:.3f}",
            ],
            [
                "Keyword router",
                _with_interval(ev.keyword.accuracy, ev.test_intervals["keyword_accuracy"]),
                f"{ev.keyword.macro_f1:.3f}",
            ],
        ],
    )

    conformal = ev.abstention
    lines += [
        "",
        f"## Abstention (split-conformal, α = {_number(ev.alpha)})",
        "",
        "The learned router answers only when its prediction set holds exactly one intent;",
        "otherwise it abstains (in the agent that would hand over to the LLM interpreter or ask).",
        "",
    ]
    lines += _table(
        ["Measure (test split)", "Value"],
        [
            [
                f"Set coverage: true intent inside the set (target ≥ {1 - ev.alpha:.0%})",
                _with_interval(conformal.set_coverage, ev.test_intervals["set_coverage"]),
            ],
            [
                "Answered: a one-intent set",
                _with_interval(conformal.answered, ev.test_intervals["answered"]),
            ],
            [
                "Accuracy when answering",
                _with_interval(conformal.answered_accuracy, ev.test_intervals["answered_accuracy"]),
            ],
            ["Mean set size", f"{conformal.mean_set_size:.2f}"],
            ["Empty sets", str(conformal.empty_sets)],
            [
                f"Keyword router answering at confidence ≥ {KEYWORD_ANSWER_CONFIDENCE}",
                _with_interval(ev.keyword_answers.answered, ev.test_intervals["keyword_answered"]),
            ],
            [
                "Keyword router accuracy when answering",
                _with_interval(
                    ev.keyword_answers.answered_accuracy,
                    ev.test_intervals["keyword_answered_accuracy"],
                ),
            ],
        ],
    )

    lines += ["", "## Recall per intent (test split)", ""]
    lines += _table(
        ["Intent", "Messages", "Learned", "Keyword"],
        [
            [
                f"{intent.value} ({SHORT[intent]})",
                str(ev.learned.recall[intent].n),
                _share(ev.learned.recall[intent]),
                _share(ev.keyword.recall[intent]),
            ]
            for intent in INTENTS
        ],
    )

    lines += ["", "## Confusion matrices (test split)", "", "Learned router, top-1:", ""]
    lines += _confusion(ev.learned)
    lines += ["", "Keyword router:", ""]
    lines += _confusion(ev.keyword)

    lines += ["", "## Slices (test split)", ""]
    lines += _table(
        ["Slice", "Messages", "Learned accuracy", "Keyword accuracy", "Set coverage", "Answered"],
        [
            [
                s.name,
                str(s.learned_accuracy.n),
                _share(s.learned_accuracy),
                _share(s.keyword_accuracy),
                _share(s.set_coverage),
                _share(s.answered),
            ]
            for s in ev.slices
        ],
    )

    if ev.repeats:
        seeds = [r.seed for r in ev.repeats]
        chosen = Counter(r.c for r in ev.repeats)
        lines += [
            "",
            f"## Repeated grouped splits ({len(ev.repeats)} more seeds)",
            "",
            "The whole pipeline (split, C, fit, calibration) again on split seeds"
            f" {min(seeds)}-{max(seeds)}.",
            f"With about {len(test_groups)} scenario groups per test split, one split's observed"
            " coverage moves a lot;",
            "the table shows its variation, not a separate guarantee for each split.",
            "",
        ]
        rows = [
            ["Learned accuracy", *_spread([r.learned_accuracy for r in ev.repeats])],
            ["Keyword accuracy", *_spread([r.keyword_accuracy for r in ev.repeats])],
            ["Set coverage", *_spread([r.set_coverage for r in ev.repeats])],
            ["Answered", *_spread([r.answered for r in ev.repeats])],
            ["Accuracy when answering", *_spread([r.answered_accuracy for r in ev.repeats])],
        ]
        lines += _table(["Measure", "Mean", "Min", "Max"], rows)
        below = sum(1 for r in ev.repeats if r.set_coverage < 1 - ev.alpha)
        macro = [r.learned_macro_f1 for r in ev.repeats]
        lines += [
            "",
            f"Learned macro-F1: mean {statistics.fmean(macro):.3f}, min {min(macro):.3f},"
            f" max {max(macro):.3f}. Splits with set coverage below {1 - ev.alpha:.0%}:"
            f" {below} of {len(ev.repeats)}. C chosen: "
            + ", ".join(f"{_number(c)} ×{chosen[c]}" for c in sorted(chosen))
            + ".",
        ]

    external = ev.external
    lines += [
        "",
        f"## External check ({len(external.rows)} messages by other teammates)",
        "",
        "Written for other purposes (Task 10, the keyword tests, the dev cases) and never used to",
        "fit or tune. It favours the keyword router, whose rules were written against most of",
        "them; it has few messages per intent, so only accuracy is reported.",
        "",
    ]
    lines += _table(
        ["Measure", "Value"],
        [
            ["Learned accuracy (top-1)", _with_interval(external.learned.accuracy)],
            ["Keyword accuracy", _with_interval(external.keyword.accuracy)],
            ["Learned set coverage", _with_interval(external.abstention.set_coverage)],
            ["Learned answered", _with_interval(external.abstention.answered)],
            [
                "Learned accuracy when answering",
                _with_interval(external.abstention.answered_accuracy),
            ],
        ],
    )
    misses = [r for r in external.rows if r.learned != r.intent or r.keyword != r.intent]
    lines += ["", "Messages either router gets wrong (top-1):", ""]
    lines += _table(
        ["Message", "Label", "Learned (set)", "Keyword"],
        [
            [
                r.text.replace("|", "\\|"),
                SHORT[r.intent],
                f"{SHORT[r.learned]} ({', '.join(SHORT[i] for i in r.learned_set) or 'empty'})",
                SHORT[r.keyword],
            ]
            for r in misses
        ],
    )
    lines += [
        "",
        "Intent abbreviations: " + ", ".join(f"{SHORT[i]} = {i.value}" for i in INTENTS) + ".",
        "",
    ]
    return "\n".join(lines)
