def _dump(data: Any) -> str:
    return json.dumps(data, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def render_all() -> dict[str, str]:
    """Return {relative file name: content} for every generated file."""
    files: dict[str, str] = {}
    for model in EXPORTED_MODELS:
        files[f"{model.__name__}.schema.json"] = _dump(model.model_json_schema(mode="validation"))

    files["serving_tables.json"] = _dump(
        {
            "contract_version": SERVING_CONTRACT_VERSION,
            "forbidden_columns": sorted(FORBIDDEN_COLUMNS),
            "required_metadata_keys": list(REQUIRED_METADATA_KEYS),
            "tables": [asdict(table) for table in SERVING_TABLES],
        }
    )

    lines = [
        "# Generated contracts",
        "",
        "Generated by `uv run poe contracts` from `src/bankagent/contracts/`.",
        "**Do not edit by hand**; CI fails (`poe contracts-check`) if these files are stale.",
        "",
        "JSON Schemas use Pydantic *validation* mode (what producers must send).",
        "",
        "| Schema | Module |",
        "|---|---|",
    ]
    for model in EXPORTED_MODELS:
        module = model.__module__.removeprefix("bankagent.contracts.")
        lines.append(f"| [`{model.__name__}`]({model.__name__}.schema.json) | `{module}` |")
    lines += [
        "",
        f"Serving DB contract v{SERVING_CONTRACT_VERSION}: "
        "[`serving_tables.json`](serving_tables.json).",
        "",
    ]
    files["README.md"] = "\n".join(lines)
    return files


def write_all(out_dir: Path) -> list[str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    files = render_all()
    for name, content in files.items():
        (out_dir / name).write_text(content, encoding="utf-8", newline="\n")
    stale = [p.name for p in out_dir.iterdir() if p.is_file() and p.name not in files]
    for name in stale:
        (out_dir / name).unlink()
    return sorted(files)


def check_all(out_dir: Path) -> list[str]:
    """Return drift problems between the generated content and the files on disk."""
    problems: list[str] = []
    files = render_all()
    for name, content in files.items():
        path = out_dir / name
        if not path.exists():
            problems.append(f"missing: {name}")
        elif path.read_text(encoding="utf-8").replace("\r\n", "\n") != content:
            problems.append(f"stale: {name}")
    if out_dir.exists():
        for path in out_dir.iterdir():
            if path.is_file() and path.name not in files:
                problems.append(f"unexpected: {path.name}")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Export shared contracts as JSON Schema.")
    parser.add_argument("--check", action="store_true", help="fail if docs/contracts is stale")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)

    if args.check:
        problems = check_all(args.out)
        if problems:
            print("docs/contracts is out of date:", file=sys.stderr)
            for problem in problems:
                print(f"  - {problem}", file=sys.stderr)
            print("Fix: uv run poe contracts, then commit docs/contracts/.", file=sys.stderr)
            return 1
        print(f"Contracts up to date ({len(render_all())} files).")
        return 0

    written = write_all(args.out)
    print(f"Wrote {len(written)} files to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
