"""Export the shared contracts as JSON Schema files under ``docs/contracts/``.

Usage:
    python -m bankagent.contracts.export          # regenerate docs/contracts/
    python -m bankagent.contracts.export --check  # exit 1 if docs/contracts/ is stale

Output is deterministic (sorted keys, LF, trailing newline) so the check is a plain text diff.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from pathlib import Path
from typing import Any

